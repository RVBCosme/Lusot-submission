"""Tests for backend/scripts/licences_py.py, the analysis image's licence check (MS7 Task 8)."""

from __future__ import annotations

import importlib.metadata
import json
from email.message import Message
from pathlib import Path

import licences_py
import pytest

POLICY = json.loads((Path(__file__).resolve().parents[2] / "scripts" / "licence-policy.json").read_text(encoding="utf-8"))

# The cases scripts/licences.test.mjs checks too, so the two tools agree.
CASES = {
    "ok": ["MIT", "(MIT OR Apache-2.0)", "BSD-3-Clause", "Apache License, Version 2.0", "Apache 2.0", "MIT OR GPL-3.0-only", "0BSD AND ISC", "BSD License OR Apache Software License", "mit or apache-2.0"],
    "review": ["MPL-2.0", "MIT AND LGPL-2.1-only", "SAM License", "SEE LICENSE IN LICENSE.md", "CC-BY-SA-4.0", "ODbL-1.0", "MPL-2.0 AND MIT"],
    "fail": ["GPL-3.0-only", "AGPL-3.0", "CC-BY-NC-4.0", "CC-BY-NC-SA-4.0", "", "Some Custom Licence", "UNLICENSED", "MIT AND GPL-2.0-or-later", "(MIT"],
}


@pytest.mark.parametrize(("expected", "expr"), [(cls, expr) for cls, exprs in CASES.items() for expr in exprs])
def test_classify_agrees_with_the_js_cases(expected, expr):
    assert licences_py.classify(expr, POLICY) == expected


def test_runtime_names_reads_a_lock_with_hashes_and_comments(tmp_path):
    lock = tmp_path / "requirements.lock.txt"
    lock.write_text(
        "# This file was autogenerated by uv\n"
        "#    uv export --no-dev\n"
        "anyio==4.15.1 \\\n"
        "    --hash=sha256:" + "a" * 64 + " \\\n"
        "    --hash=sha256:" + "b" * 64 + "\n"
        "    # via httpx\n"
        "colorama==0.4.6 ; sys_platform == 'win32' \\\n"
        "    --hash=sha256:" + "c" * 64 + "\n"
        "pywin32==311 ; platform_system == \"Windows\" and python_full_version >= '3.13'\n"
        "exceptiongroup==1.3.0 ; python_full_version < '3.11'\n"
        "uvloop==0.21.0 ; sys_platform != 'win32' and implementation_name == 'cpython'\n"
        "Typing_Extensions==4.16.0\n",
        encoding="utf-8",
    )
    assert licences_py.runtime_names(lock) == [
        ("anyio", "4.15.1"),
        ("exceptiongroup", "1.3.0"),
        ("uvloop", "0.21.0"),
        ("Typing_Extensions", "4.16.0"),
    ]


def fake_metadata(**fields):
    msg = Message()
    for key, value in fields.items():
        for item in value if isinstance(value, list) else [value]:
            msg[key.replace("_", "-")] = item
    return msg


@pytest.mark.parametrize(
    ("fields", "expected", "cls"),
    [
        ({"License_Expression": "MIT OR Apache-2.0", "License": "ignored"}, "MIT OR Apache-2.0", "ok"),
        ({"License": "Apache 2.0\n\nThe rest of a long licence text."}, "Apache 2.0", "ok"),
        (
            {"Classifier": ["Programming Language :: Python", "License :: OSI Approved :: MIT License", "License :: OSI Approved :: Apache Software License"]},
            "MIT License OR Apache Software License",
            "ok",
        ),
        (
            {"License": "Dual License", "Classifier": ["License :: OSI Approved :: BSD License", "License :: OSI Approved :: Apache Software License"]},
            "BSD License OR Apache Software License",
            "ok",
        ),
        ({"Name": "nothing"}, "", "fail"),
    ],
)
def test_licence_of_reads_each_metadata_form(monkeypatch, fields, expected, cls):
    monkeypatch.setattr(importlib.metadata, "metadata", lambda name: fake_metadata(**fields))
    assert licences_py.licence_of("pkg") == expected
    assert licences_py.classify(expected, POLICY) == cls


def test_main_fails_on_a_copyleft_package_and_a_version_mismatch(monkeypatch, tmp_path, capsys):
    lock = tmp_path / "requirements.lock.txt"
    lock.write_text("good==1.0\nbad==2.0\nold==3.0\nmissing==4.0\n", encoding="utf-8")
    licences = {"good": "MIT", "bad": "GPL-3.0-only", "old": "MIT"}
    versions = {"good": "1.0", "bad": "2.0", "old": "2.9"}

    def version(name):
        if name not in versions:
            raise importlib.metadata.PackageNotFoundError(name)
        return versions[name]

    monkeypatch.setattr(licences_py, "licence_of", lambda name: licences[name])
    monkeypatch.setattr(importlib.metadata, "version", version)
    assert licences_py.main([str(lock)]) == 1
    out = capsys.readouterr().out
    assert "| good | 1.0 | MIT | analysis image | ok |" in out
    assert "FAIL: bad==2.0 (GPL-3.0-only)" in out
    assert "FAIL: old==3.0 is installed at 2.9" in out
    assert "FAIL: missing==4.0 is not installed" in out


def test_main_passes_with_only_ok_and_review(monkeypatch, tmp_path, capsys):
    lock = tmp_path / "requirements.lock.txt"
    lock.write_text("a==1.0\nb==2.0\n", encoding="utf-8")
    monkeypatch.setattr(licences_py, "licence_of", {"a": "MIT", "b": "SAM License"}.__getitem__)
    monkeypatch.setattr(importlib.metadata, "version", {"a": "1.0", "b": "2.0"}.__getitem__)
    assert licences_py.main([str(lock)]) == 0
    out = capsys.readouterr().out
    assert "REVIEW: b==2.0 (SAM License)" in out
